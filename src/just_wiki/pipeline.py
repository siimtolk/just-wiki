"""The pipeline steward: merges inbox notes into pages with small, separate LLM calls instead of one agent session.

Built for local models with a bounded context: code does everything mechanical (finding candidate pages, grouping,
editing, checking, moving notes, logging, committing); the model only judges, in short calls that each start fresh.

  0. code    owner / postpone / drop answers are table edits (mechanical_answers); a decide answer removes its row
             and becomes a decision note (decision_answers), and so does a drop, so the decision lands on a page;
             a note with the same text as an earlier one is discarded without a model call
  1. route   per note (skipped when the note's `topic` names a page): the note + candidate pages from the wiki's
             own search, and the pages this run plans to create → merge into page(s) | new page | question | discard
  2. edit    per page: the page (generated blocks collapsed to one line) + all of tonight's notes for it → only the
             sections that change, as <edit>/<add> blocks; code applies them and restores the blocks
  3. check   code: frontmatter, type, sources (old ∪ notes), links, generated blocks unchanged, no lost facts
             (numbers, paths, ids) unless a note replaces them; up to two retries with the problems (a group that
             still fails is merged one note at a time), else the notes wait. Coverage: every number, version, path,
             file name, date and time of a note must be on a page after its last merge (dates and times on the
             pages it went into); one retry, then the page is kept and the gaps are logged (and listed unchecked)
  3b. verify code (verify.py): the notes' claims checked against the host where code can (paths, units, your own
             commands). The page stays `verified` only if every note passed; otherwise it becomes `draft` and goes
             on the unchecked list, with new disagreements and other pages that still hold a replaced value, which
             the agent steward re-checks (daily, or once an entry has waited an hour)
  4. file    code: compare-and-swap write (a page someone edited meanwhile is merged again on its new text), a log
             line per note, a commit per page with only the files this step wrote; a note leaves the inbox as soon
             as every page it feeds is committed (logs/pipeline-progress.json survives a crash)

Answers to open questions that need judgement (decide, investigate), questions to settle and stale or unchecked pages
go to the agent steward when `[steward] rest = "agent"`.

Config (wiki.toml):

  [steward]
  mode = "pipeline"
  rest = "agent"                    # or "skip"
  [steward.llm]                     # any OpenAI-compatible chat endpoint
  base_url = "http://localhost:8080/v1"
  model = "your-model-id"
  api_key_file = "secrets/key.txt"  # a file holding the bearer key ({root} and ~ expand), never the key itself
  reasoning_effort = "low"          # sent only when set; route_effort / edit_effort override it per call kind
  route_max_tokens = 2000
  edit_max_tokens = 16000
  timeout_s = 900
  max_page_chars = 30000            # a bigger page is left to the agent steward (its notes stay pending)…
  overflow = "agent"                # …or "split": its new notes go to a linked page <id>-2 (default when rest = "skip")
"""
