# ---------------------------------------------------------------- the model

class LLM:
    """OpenAI-compatible chat completions; counts calls and tokens for the steward log."""

    def __init__(self, c):
        self.c = c
        self.calls = 0
        self.usage = {"input_tokens": 0, "output_tokens": 0}
        self.seconds = 0.0
        self.finish = None
        key = c.get("api_key_file")
        self.key = Path(config.expand(key, w.ROOT)).read_text().strip() if key else ""

    def chat(self, system, user, kind="edit"):
        effort = self.c.get(f"{kind}_effort", self.c.get("reasoning_effort"))
        limit = self.c.get(f"{kind}_max_tokens", self.c.get("max_tokens", 2000 if kind == "route" else 16000))
        body = {"model": self.c["model"], "messages": [{"role": "system", "content": system},
                                                       {"role": "user", "content": user}], "max_tokens": int(limit)}
        if effort:
            body["reasoning_effort"] = effort
        headers = {"Content-Type": "application/json"}
        if self.key:
            headers["Authorization"] = f"Bearer {self.key}"
        url = self.c["base_url"].rstrip("/") + "/chat/completions"
        last = None
        for attempt in range(3):
            t = time.time()
            try:
                req = urllib.request.Request(url, data=json.dumps(body).encode(), headers=headers)
                with urllib.request.urlopen(req, timeout=int(self.c.get("timeout_s", 900))) as r:
                    res = json.loads(r.read())
                self.calls += 1
                self.seconds += time.time() - t
                u = res.get("usage") or {}
                self.usage["input_tokens"] += u.get("prompt_tokens", 0)
                self.usage["output_tokens"] += u.get("completion_tokens", 0)
                self.finish = res["choices"][0].get("finish_reason")
                return res["choices"][0]["message"].get("content") or ""
            except (urllib.error.URLError, OSError, KeyError, ValueError) as e:
                last = e
                time.sleep(10 * (attempt + 1))
        raise RuntimeError(f"LLM call failed: {last}")


def json_in(text):
    m = re.search(r"\{.*\}", text, re.S)
    if not m:
        raise ValueError("no JSON object in the reply")
    return json.loads(m.group(0))


def tagged(text, tag):
    m = re.search(rf"<{tag}>\s*(.*?)\s*</{tag}>", text, re.S)
    return m.group(1) if m else None


