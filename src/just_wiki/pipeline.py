# ---------------------------------------------------------------- sections and generated blocks

def collapse(body):
    """Generated blocks → one placeholder line each (smaller prompts; the model can't alter them)."""
    blocks = {}

    def repl(m):
        blocks[m.group(1)] = m.group(0)
        return PLACEHOLDER.format(name=m.group(1))
    return LIVE.sub(repl, body), blocks


def expand(body, blocks):
    return PLACEHOLDER_RX.sub(lambda m: blocks.get(m.group(1), m.group(0)), body)


def sections(body):
    """[(heading line or "", text)] in order; the text runs to the next heading of any level."""
    out, last, pos = [], "", 0
    for m in HEADING.finditer(body):
        out.append((last, body[pos:m.start()]))
        last, pos = m.group(0), m.end() + 1
    out.append((last, body[pos:]))
    return out


FORMAT_HELP = ('reply with only the changed sections, as <edit heading="<an exact heading line>">the whole new section '
               'text</edit> (or <add after="…" heading="## …">…</add>), and <why>one line</why>; never the whole page')


def normalize(reply):
    """Forgive what local models get wrong in the reply format: code fences, single-quoted attributes."""
    reply = re.sub(r"(?m)^```[\w-]*[ \t]*\n?", "", reply)
    return re.sub(r"""(<(?:edit|add)\b[^>]*?)\b(heading|after)='([^']*)'""",
                  lambda m: f'{m.group(1)}{m.group(2)}="{m.group(3)}"', reply)


def whole_page(body, reply):
    """A reply that is the whole page body instead of edit blocks (it starts at the page's first heading line, and
    has most of its headings): that body, else None. check_page still guards it like any edit."""
    heads = [h for h, _ in sections(body) if h]
    text = re.sub(r"<(why|summary)>.*?</\1>", "", reply, flags=re.S)
    m = re.search(rf"(?m)^{re.escape(heads[0])}[ \t]*$", text) if heads else None
    if not m:
        return None
    new = text[m.start():].strip() + "\n"
    have = {h for h, _ in sections(new) if h}
    return new if len(have & set(heads)) >= max(1, len(heads) * 2 // 3) else None


def apply_edits(body, reply, finish=None):
    """Apply <edit>/<add> blocks to body. Returns (new body, problems)."""
    reply = normalize(reply)
    if not EDIT.search(reply) and not ADD.search(reply):
        if finish == "length":
            return body, ["your reply was cut off at the length limit: " + FORMAT_HELP]
        new = whole_page(body, reply)
        if new:
            return new, []
        return body, ["no <edit> or <add> block in the reply: " + FORMAT_HELP]
    secs = sections(body)
    heads = [h for h, _ in secs]
    problems = []
    for heading, text in EDIT.findall(reply):
        h = heading.strip()
        if h not in heads or not h:
            problems.append(f"no heading {h!r} on the page (use an exact heading line)")
            continue
        secs[heads.index(h)] = (h, text.strip() + "\n\n")
    for after, heading, text in ADD.findall(reply):
        a, h = after.strip(), heading.strip()
        if not HEADING.fullmatch(h):
            problems.append(f"new heading {h!r} must be a markdown heading like '## Name'")
            continue
        if h in heads:                             # it exists already: treat it as an edit
            secs[heads.index(h)] = (h, text.strip() + "\n\n")
            continue
        i = heads.index(a) if a in heads else len(heads) - 1
        secs.insert(i + 1, (h, text.strip() + "\n\n"))
        heads.insert(i + 1, h)
    if finish == "length":
        problems.append("your reply was cut off at the length limit (a section may be incomplete): " + FORMAT_HELP)
    new = "".join((h + "\n" if h else "") + t for h, t in secs)
    return re.sub(r"\n{3,}", "\n\n", new), problems


# ---------------------------------------------------------------- checks

def facts(text):
    return set(FACT.findall(LIVE.sub("", text)))


def note_facts(body):
    """What a note must not lose: numbers, versions, paths, ids, code, file names, dates and times (not bare years,
    not paths into the inbox)."""
    out = set()
    for f in facts(body) | set(DATE.findall(body)) | set(FILENAME.findall(body)):
        v = f.strip("`").strip()
        if len(v) >= 2 and not YEARISH.match(v) and "inbox/" not in v and "_processed" not in v:
            out.add(v)
    return out


def when(v):
    return bool(DATE.fullmatch(v) or CLOCK.match(v))


def uncovered(cover, pid, page):
    """{note id: [facts]} for the notes in `cover` (this is the last page they go into): each fact of the note that is
    on no page after this merge. A date or time must be on a page the note went into; anything else may be anywhere."""
    if not cover:
        return {}
    others = {w.page_id(p): p.read_text(encoding="utf-8") for p in w.pages() if w.page_id(p) != pid}
    everything = page + "\n".join(others.values())
    out = {}
    for n in cover:
        mine = page + "\n".join(others.get(o, "") for o in (n.get("needs") or set()) - {pid})
        miss = sorted(v for v in note_facts(n["body"]) if v not in (mine if when(v) else everything))
        if miss:
            out[n["id"]] = miss[:20]
    return out


def coverage_problem(missing):
    return [f"these facts of note {nid} are on no page after this merge: {', '.join(vals)}. Put each one where it "
            "belongs on this page (a short line is enough), with the date or time it goes with"
            for nid, vals in missing.items()]


def check_page(old_text, new_text, notes_text, page_ids, folder):
    """Problems with a merged page (empty list = fine). The checks are code, not the model's word."""
    problems = []
    meta, body = w.split(new_text)
    if "_error" in meta or not meta:
        return [f"the frontmatter does not parse ({meta.get('_error', 'missing')})"]
    for k in ("title", "type", "status", "summary", "updated"):
        if not meta.get(k):
            problems.append(f"frontmatter key `{k}` is missing")
    if folder in w.TYPES and meta.get("type") != w.TYPES[folder]:
        problems.append(f"type must be `{w.TYPES[folder]}` for {folder}/")
    for ref in w.links(body):
        if ref not in page_ids and not w.resolve(ref):
            problems.append(f"broken link [[{ref}]]")
    if old_text:
        old_body = w.split(old_text)[1]
        old_blocks = {m.group(1): m.group(0) for m in LIVE.finditer(old_body)}
        new_blocks = {m.group(1): m.group(0) for m in LIVE.finditer(body)}
        for name, block in old_blocks.items():
            if new_blocks.get(name) != block:
                problems.append(f"the line <!-- live:{name} (generated…) --> was changed or removed: keep it as it is")
        lost = sorted(f for f in facts(old_body) - facts(body) if f not in notes_text)
        if len(lost) > max(2, len(facts(old_body)) // 10):
            problems.append("these facts from the page are gone, and no note replaces them: " + ", ".join(lost[:25]))
        if len(body) < 0.6 * len(old_body):
            problems.append(f"the page shrank from {len(old_body)} to {len(body)} characters: keep what the notes "
                            "don't change")
    return problems


def finish_meta(new_text, old_text, note_metas, agent, folder=None, summary=None):
    """Frontmatter the code owns: sources = old ∪ model's ∪ notes', updated, updated_by; status kept (a new page is
    a draft); type from the folder; summary only when the model gave a new one."""
    meta, body = w.split(new_text)
    old_meta = w.split(old_text)[0] if old_text else {}
    srcs = []
    for s in [*(old_meta.get("sources") or []), *(meta.get("sources") or []),
              *[s for m in note_metas for s in (m.get("sources") or [])]]:
        if s and s not in srcs:
            srcs.append(s)
    meta["sources"] = srcs
    meta["updated"] = date.today().isoformat()
    meta["updated_by"] = agent
    if old_meta.get("status"):
        meta["status"] = old_meta["status"] if old_meta["status"] != "stale" else "draft"
    elif meta.get("status") not in w.STATUSES:
        meta["status"] = "draft"
    if folder in w.TYPES:
        meta["type"] = w.TYPES[folder]
    if summary:
        meta["summary"] = " ".join(summary.split())[:200]
    return w.dump(meta, body)


# ---------------------------------------------------------------- the steps

def note_block(n, pid=None):
    m = n["meta"]
    also = sorted((n.get("needs") or set()) - {pid}) if pid else []
    return (f"--- note {n['id']} ({m.get('created')}, by {m.get('agent')}, kind {m.get('kind')}, "
            f"sources: {', '.join(map(str, m.get('sources') or []))}"
            + (f"; it also goes to {', '.join(also)}" if also else "") + f")\n{n['body'].strip()}\n")


def content_page(path):
    """A page notes can be merged into: one in the page folders, not status, index, log or a note."""
    return bool(path) and path.relative_to(w.ROOT).parts[0] in w.PAGE_DIRS


ALWAYS_TYPES = ("person", "preference")       # folders of these types are always shown to the router (they are few)
ALWAYS_MAX = 20


def route_rules():
    """Per-folder routing rules for the folders a wiki has (by type)."""
    by_type = {t: d for d, t in w.TYPES.items()}
    rules = []
    if "person" in by_type:
        rules.append(f"Who someone is (background, relationships, situation) goes to their page in {by_type['person']}/.")
    if "preference" in by_type:
        rules.append(f"How someone wants things (tastes, standing instructions, how to answer them) goes to "
                     f"{by_type['preference']}/.")
    if "decision" in by_type:
        rules.append(f"A {by_type['decision']}/ page holds one decision: merge into it only what changes that "
                     "decision; facts about the thing decided go to that thing's own page.")
    return " ".join(rules) + (" " if rules else "")


def candidates(n, planned):
    """(rows by folder, planned line): the search hits plus every page of the always-shown folders; pages planned
    in this run are named only by id, so a note joins one only by choosing that slug for the same thing."""
    query = f"{n['meta'].get('title', '')} {n['body'][:400]}"
    hits = mcp_server.search(query, limit=15, include_inbox=False)          # sections: several per page
    ids = list(dict.fromkeys(p for p in re.findall(r"(?m)^\d+\. (\S+) ", hits) if content_page(w.resolve(p))))[:CANDIDATES]
    for d, t in w.TYPES.items():
        if t in ALWAYS_TYPES and (w.ROOT / d).is_dir():
            ids += [w.page_id(p) for p in sorted((w.ROOT / d).glob("*.md"))[:ALWAYS_MAX]]
    rows = {}
    for pid in dict.fromkeys(ids):
        meta = w.split(w.resolve(pid).read_text(encoding="utf-8"))[0]
        rows.setdefault(pid.split("/")[0], []).append(f"- {pid} — {meta.get('title', '')} — {meta.get('summary', '')}")
    text = "\n".join(f"{d}/:\n" + "\n".join(r) for d, r in sorted(rows.items(), key=lambda x: w.PAGE_DIRS.index(x[0])
                                                                     if x[0] in w.PAGE_DIRS else 99))
    plan = (f"PLANNED (new pages this run, not written yet): {', '.join(planned)}\n" if planned else "")
    return text or "(no matching pages)", plan


def route(llm, n, folders, planned):
    topic = n["meta"].get("topic")
    if topic and content_page(w.resolve(str(topic))) and n["meta"].get("kind") != "question":
        return {"action": "merge", "pages": [w.page_id(w.resolve(str(topic)))], "why": "topic given by the note"}
    rows, plan = candidates(n, planned)
    r = {}
    for _attempt in range(2):
        r = json_in(llm.chat(SYSTEM, ROUTE.format(created=n["meta"].get("created"), agent=n["meta"].get("agent"),
                                                  kind=n["meta"].get("kind"), note=n["body"].strip()[:6000],
                                                  candidates=rows, planned=plan, rules=route_rules(),
                                                  folders=w.folders_text()), kind="route"))
        a = r.get("action")
        if a == "merge":
            pages = []
            for p in (r.get("pages") or [])[:MAX_ROUTE_PAGES]:
                found = w.resolve(str(p))
                if str(p) in planned:
                    pages.append(str(p))
                elif content_page(found):
                    pages.append(w.page_id(found))
            if pages:
                return {**r, "pages": pages}
        elif a == "new" and r.get("folder") in folders and re.fullmatch(r"[a-z0-9][a-z0-9-]{1,60}", str(r.get("slug"))):
            return r
        elif a in ("question", "discard"):
            return r
    return {"action": "pending", "why": f"routing failed: {str(r)[:200]}"}


def sections_of(body):
    """(preamble, [(heading line, text with its heading)]) at the '## ' headings of a page body."""
    parts = re.split(r"(?m)^(?=## )", body)
    pre, secs = (parts[0], parts[1:]) if not parts[0].startswith("## ") else ("", parts)
    return pre, [(p.splitlines()[0].strip(), p.rstrip("\n") + "\n") for p in secs]


def plan_split(llm, pid, text, limit):
    """The model's moves for an oversized page: [(heading, target id, title or None)], why."""
    meta, body = w.split(text)
    pre, secs = sections_of(body)
    keeps_text = len(re.sub(r"(?m)^# .*$", "", pre).strip()) > 0     # the top part stays, so every section may go
    if not secs or (len(secs) < 2 and not keeps_text):
        return [], "no section that can move"
    listing = "\n".join(f"- {h} — {len(t)} — {' '.join(t.split()[len(h.split()):][:25])}" for h, t in secs)
    others = "\n".join(f"- {w.page_id(p)} — {w.split(p.read_text(encoding='utf-8'))[0].get('title', '')}"
                        for p in w.pages() if content_page(p) and w.page_id(p) != pid)
    r = json_in(llm.chat(SYSTEM, SPLIT_PROMPT.format(page_id=pid, size=len(text), limit=limit, sections=listing,
                                                     pages=others or "(none)", folders=w.folders_text(),
                                                     rules=route_rules()), kind="split"))
    heads = {h: t for h, t in secs}
    moves = []
    for m in r.get("moves") or []:
        h = str(m.get("heading", "")).strip()
        if h not in heads or any(x[0] == h for x in moves):
            continue
        to = str(m.get("to") or "")
        if to and content_page(w.resolve(to)) and w.page_id(w.resolve(to)) != pid:
            moves.append((h, w.page_id(w.resolve(to)), None))
        elif m.get("folder") in w.PAGE_DIRS and re.fullmatch(r"[a-z0-9][a-z0-9-]{1,60}", str(m.get("slug"))):
            key = f"{m['folder']}/{m['slug']}"
            if key == pid:
                continue
            moves.append((h, w.page_id(w.resolve(key)) if w.resolve(key) else key, m.get("title") or h[3:]))
    if len(moves) >= len(secs) and not keeps_text:  # the page must keep something
        moves = moves[:len(secs) - 1]
    return moves, str(r.get("why", ""))


MOVED_MARK = re.compile(r"(?m)^\(Moved here from \[\[[^\]]+\]\]\.\)[ \t]*\n*")


def apply_split(pid, text, moves, agent):
    """Move the sections: copied as they are (nothing is rewritten, so nothing is lost), appended to an existing
    page or opening a new one, and the old page links to where each went. Returns {path: new text}."""
    meta, body = w.split(text)
    pre, secs = sections_of(body)
    by_target = {}
    for h, to, title in moves:
        by_target.setdefault(to, {"title": title, "heads": []})["heads"].append(h)
    moved = {h for h, _, _ in moves}
    keep = [t for h, t in secs if h not in moved]
    see = [f"- [[{to}]]: {', '.join(x[3:] for x in spec['heads'])}" for to, spec in by_target.items()]
    kept = "".join(keep)
    if re.search(r"(?m)^## See also\s*$", kept):
        kept = re.sub(r"(?m)^(## See also\s*\n)", lambda m_: m_.group(1) + "\n".join(see) + "\n", kept, count=1)
    else:
        kept = kept.rstrip("\n") + "\n\n## See also\n\n" + "\n".join(see) + "\n"
    out = {w.ROOT / f"{pid}.md": finish_meta(w.dump(meta, pre.rstrip("\n") + "\n\n" + kept), text, [], agent)}
    texts = {h: t for h, t in secs}
    for to, spec in by_target.items():
        part = "".join(texts[h] if texts[h].endswith("\n\n") else texts[h] + "\n" for h in spec["heads"]).rstrip("\n")
        part = MOVED_MARK.sub("", part).strip("\n")       # markers of earlier moves do not travel with the text
        path = w.resolve(to)
        if path:
            if not part.strip():
                continue                                    # only markers were left: nothing to move
            old = path.read_text(encoding="utf-8")
            m2, b2 = w.split(old)
            m2["sources"] = list(dict.fromkeys([*(m2.get("sources") or []), *(meta.get("sources") or [])]))
            mark = f"(Moved here from [[{pid}]].)"
            new = w.dump(m2, b2.rstrip("\n") + f"\n\n{part}\n" + ("" if mark in b2 else f"\n{mark}\n"))   # once per source page
            out[path] = finish_meta(new, old, [], agent)
        else:
            folder = to.split("/")[0]
            title = spec["title"] or to.split("/")[-1].replace("-", " ").capitalize()
            first = re.sub(r"\s+", " ", re.sub(r"(?m)^#+ .*$", "", part)).strip()
            m2 = {"title": title, "type": w.TYPES.get(folder, ""), "status": meta.get("status", "draft"),
                  "summary": (first[:150].rsplit(" ", 1)[0] + "…") if len(first) > 150 else first,
                  "sources": list(meta.get("sources") or [])}
            out[w.ROOT / f"{to}.md"] = finish_meta(w.dump(m2, f"# {title}\n\nFrom [[{pid}]].\n\n{part}\n"), None,
                                                   [], agent, folder=folder)
    return out


def save_failure(pid, reply, problems):
    """The last bad reply, for finding out why a merge failed (logs/pipeline-failures/)."""
    d = w.ROOT / "logs" / "pipeline-failures"
    d.mkdir(parents=True, exist_ok=True)
    f = d / f"{time.strftime('%Y-%m-%d-%H%M%S')}-{pid.replace('/', '__')}.txt"
    f.write_text("PROBLEMS:\n- " + "\n- ".join(problems) + "\n\nREPLY:\n" + (reply or ""), encoding="utf-8")


def merge_loop(llm, pid, notes, cover, ask, build):
    """The model's reply → page, checked by code, up to ATTEMPTS calls. The coverage check gets one retry; when that
    retry still leaves gaps (or breaks a hard check), the best page passing the hard checks is kept and the gaps are
    returned. Returns (page, why, gaps) or (None, why, {})."""
    problems, found, reply, best, coverage_tried = "", [], "", None, False
    for _attempt in range(ATTEMPTS):
        reply = llm.chat(SYSTEM, ask(problems), kind="edit")
        page, found = build(reply, llm.finish)
        if not found:
            gaps = uncovered(cover, pid, page)
            why = (tagged(reply, "why") or "").strip()
            if not gaps:
                return page, why, {}
            if best is None or sum(map(len, gaps.values())) < sum(map(len, best[2].values())):
                best = (page, why, gaps)
            if coverage_tried:
                break
            coverage_tried = True
            found = coverage_problem(gaps)
        elif best:                                  # the coverage retry broke the page: keep the earlier one
            break
        problems = "\nYour last reply had these problems; fix them:\n- " + "\n- ".join(found)
    if best:
        return best
    save_failure(pid, reply, found)
    return None, "; ".join(found), {}


def edit_page(llm, pid, notes, agent, page_ids, old_text, cover=()):
    """The page with tonight's notes merged in: (page, why, gaps), or (None, why, {})."""
    folder = pid.split("/")[0]
    meta, body = w.split(old_text)
    small, blocks = collapse(body)
    heads = [h for h, _ in sections(small) if h]
    notes_text = "\n".join(note_block(n, pid) for n in notes)

    def ask(problems):
        return EDIT_PROMPT.format(page_id=pid, page=small, notes=notes_text, headings=" | ".join(heads),
                                  page_ids=", ".join(page_ids), problems=problems)

    def build(reply, finish):
        new_small, found = apply_edits(small, reply, finish)
        if found:
            return None, found
        page = finish_meta(w.dump(meta, expand(new_small, blocks)), old_text, [n["meta"] for n in notes], agent,
                           folder, tagged(normalize(reply), "summary"))
        return page, check_page(old_text, page, notes_text, page_ids, folder)
    return merge_loop(llm, pid, notes, cover, ask, build)


def new_page(llm, pid, title, notes, agent, page_ids, cover=()):
    folder = pid.split("/")[0]
    notes_text = "\n".join(note_block(n, pid) for n in notes)

    def ask(problems):
        return NEW_PROMPT.format(page_id=pid, type=w.TYPES[folder], title=title, notes=notes_text,
                                 page_ids=", ".join(page_ids), problems=problems)

    def build(reply, finish):
        page = tagged(normalize(reply), "page")
        if not page:
            return None, ["your reply was cut off at the length limit: write a shorter page" if finish == "length"
                          else "no <page>…</page> in the reply"]
        page = finish_meta(page.strip() + "\n", None, [n["meta"] for n in notes], agent, folder)
        return page, check_page(None, page, notes_text, page_ids, folder)
    return merge_loop(llm, pid, notes, cover, ask, build)


def add_question(r, n):
    status = w.ROOT / "status.md"
    text = status.read_text(encoding="utf-8")
    row = (f"| **{r.get('question', n['meta'].get('title'))}** — {r.get('context', '')} (from note {n['id']}) | "
           f"{r.get('owner') or '?'} |")
    m = re.search(r"(## Open questions\n(?:.*\n)*?\|---\|---\|\n(?:\|.*\|\n)*)", text)
    if m:
        text = text.replace(m.group(1), m.group(1) + row + "\n")
    else:
        text += "\n## Open questions\n\n| Question | Owner |\n|---|---|\n" + row + "\n"
    status.write_text(text, encoding="utf-8")


def move(n):
    """The note to inbox/_processed/; returns both paths (for the commit)."""
    dst = w.INBOX / "_processed" / n["path"].parent.name / n["path"].name
    dst.parent.mkdir(parents=True, exist_ok=True)
    n["path"].rename(dst)
    return [n["path"], dst]


def git(*args):
    return subprocess.run(["git", "-C", str(w.ROOT), *args], capture_output=True, text=True)


def commit(message, paths):
    """Commit only these paths (deletions included): never someone else's work in progress."""
    if not (w.ROOT / ".git").exists():
        return
    rel = sorted({str(Path(p).relative_to(w.ROOT)) for p in paths if str(p).startswith(str(w.ROOT))})
    tracked = set(git("ls-files", "--", *rel).stdout.split()) if rel else set()
    rel = [r for r in rel if (w.ROOT / r).exists() or r in tracked]   # a never-committed note's old path: skip it
    if not rel:
        return
    git("add", "-A", "--", *rel)
    if git("diff", "--cached", "--quiet", "--", *rel).returncode:
        r = git("commit", "-qm", message, "--", *rel)
        if r.returncode:
            raise RuntimeError(f"git commit failed: {(r.stderr or r.stdout).strip()[:300]}")


def run_tag():
    """steward-<tag>.json: one log per run (two runs on one day must not overwrite each other)."""
    return time.strftime("%Y-%m-%d-%H%M%S")


def norm_hash(body):
    return hashlib.sha1(re.sub(r"\s+", " ", body).strip().lower().encode()).hexdigest()


def processed_hashes():
    d = w.INBOX / "_processed"
    return {norm_hash(w.split(p.read_text(encoding="utf-8"))[1]) for p in d.rglob("*.md")} if d.is_dir() else set()


class Progress:
    """logs/pipeline-progress.json: the pages each note already went into (a crash, or a failed second page, must not
    merge it twice into the first)."""

    def __init__(self):
        self.f = w.ROOT / "logs" / "pipeline-progress.json"
        try:
            self.d = json.loads(self.f.read_text())
        except (OSError, ValueError):
            self.d = {}

    def done(self, note_id):
        return set(self.d.get(note_id, []))

    def add(self, note_id, pid):
        if pid not in self.d.setdefault(note_id, []):
            self.d[note_id].append(pid)
        self.save()

    def forget(self, note_id):
        if self.d.pop(note_id, None) is not None:
            self.save()

    def save(self):
        self.f.parent.mkdir(exist_ok=True)
        self.f.write_text(json.dumps(self.d, indent=1) + "\n")


def plain(text):
    text = re.sub(r"\[\[([^\]|]+)(?:\|[^\]]*)?\]\]", r"\1", questions.REMINDER.sub("", questions.base_text(text)))
    return re.sub(r"[*`_]", "", text).strip()


def decision_note(a, q, line):
    """A note that records a person's answer on a page: the pipeline routes it like any note (to the page the question
    links, else wherever it fits, or a new decisions/ page). Returns the new note's path, or None."""
    from . import notes
    linked = [r for r in re.findall(r"\[\[([^\]|]+)", q["text"]) if content_page(w.resolve(r))]
    bold = re.match(r"\s*\*\*(.+?)\*\*", questions.REMINDER.sub("", questions.base_text(q["text"])))
    asked = plain(bold.group(1)) if bold else plain(q["text"])      # the question, not its context and dates
    short = asked
    short = short[:80].rsplit(" ", 1)[0] + "…" if len(short) > 82 else short
    who, when_ = a.get("agent") or "someone", str(a.get("created") or "")[:10]
    verb = {"decide": "Decided", "drop": "Dropped"}[a["action"]]
    body = (f"On {when_} {who} answered the open question “{asked}” (q-{q['id']} in status.md): "
            f"{line}\n")
    before = set(w.inbox_notes())
    ok, _msg = notes.submit("steward", "decision", f"{verb}: {short}", body,
                            [f"answer {a['file']}", "status.md open questions"],
                            topic=w.page_id(w.resolve(linked[0])) if linked else "")
    new = set(w.inbox_notes()) - before
    return next(iter(new)) if ok and new else None


def _file_answer(a, line, extra):
    path = Path(a["path"])
    dst = w.INBOX / "_processed" / path.parent.name / path.name
    dst.parent.mkdir(parents=True, exist_ok=True)
    path.rename(dst)
    w.append_log("steward", line)
    commit(f"steward: {line.split(' →')[0].split(':')[0]}", [w.ROOT / "status.md", w.LOG, path, dst, *extra])


def mechanical_answers(out=print):
    """Carry out the answers to open questions that are plain table edits (owner, postpone, drop) in code, so the
    agent steward is started only for decide and investigate. A drop also leaves a decision note, so the reason
    ends up on a page and not only in the log. Returns how many were carried out."""
    from .steward import git_lock
    done = 0
    for _qid, answers in sorted(questions.answers().items()):
        for a in sorted(answers, key=lambda x: str(x.get("created", ""))):
            if a.get("action") not in questions.MECHANICAL:
                continue
            with git_lock():
                q = questions.find(str(a.get("answers")))
                ok, line = questions.carry_out(a)
                if not ok:
                    out(f"  answer {a['file']}: left for the agent steward ({line})")
                    continue
                extra = []
                if a["action"] == "drop" and q:
                    said = (a.get("said") or "").strip()
                    trace = decision_note(a, q, "drop it" + (f": {said}" if said else " (no reason given)"))
                    extra = [trace] if trace else []
                _file_answer(a, line, extra)
                done += 1
    if done:
        out(f"{done} answer(s) carried out in code (owner, postpone, drop)")
    return done


def decision_answers(out=print):
    """A decide answer: code removes the row and writes the decision as a note, which the pipeline then merges into
    the page it concerns (or a new decisions/ page) like any other note, so no agent is needed for it. Returns how
    many were carried out."""
    from .steward import git_lock
    done = 0
    for _qid, answers in sorted(questions.answers().items()):
        for a in sorted(answers, key=lambda x: str(x.get("created", ""))):
            said = (a.get("said") or "").strip()
            if a.get("action") != "decide" or not said:
                continue
            with git_lock():
                q = questions.find(str(a.get("answers")))
                if not q:
                    _file_answer(a, f"decide q-{a.get('answers')}: the row was already gone", [])
                    done += 1
                    continue
                trace = decision_note(a, q, said)
                if not trace:
                    out(f"  answer {a['file']}: left for the agent steward (the decision note was rejected)")
                    continue
                questions.edit_row(q["id"], remove=True)
                _file_answer(a, f"decide q-{q['id']} → {w.page_id(trace)}: {said[:120]}", [trace])
                done += 1
    if done:
        out(f"{done} decision(s) written as notes for the pipeline")
    return done


def run(out=print):
    """Merge every waiting note (not answers to open questions). Writes logs/steward-<date>.json in the shape of
    `claude -p --output-format json`. Returns 0, or 1 when notes had to stay in the inbox."""
    from .steward import git_lock
    c = w.cfg()["steward"]
    llm = LLM(c.get("llm") or {})
    agent = w.cfg()["wiki"].get("agent") or "steward"
    # Answers to open questions are the agent steward's. Except an older decision note that names its question only in
    # its file name (no `answers:` field) when no such row exists: nobody would ever carry it out, so it is merged as
    # an ordinary decision note below (a replayed wiki has the notes but not the rows).
    answer_files = {a["path"] for qid, qs in questions.answers().items() for a in qs
                    if questions.find(qid) or a.get("answers")}
    seen = processed_hashes()
    progress = Progress()
    notes = []
    for p in w.inbox_notes():
        if str(p) in answer_files:
            continue
        meta, body = w.split(p.read_text(encoding="utf-8"))
        if meta.get("answers"):
            continue
        notes.append({"path": p, "id": p.stem, "meta": meta, "body": body})
    notes.sort(key=lambda n: (str(n["meta"].get("created", "")), n["id"]))
    folders = list(w.PAGE_DIRS)
    t0 = time.time()
    summary = {"merged": 0, "new": 0, "question": 0, "discard": 0, "pending": 0}

    def settle(n, verb, line, extra_paths=()):
        with git_lock():
            paths = move(n)
            w.append_log("steward", line)
            commit(f"steward: {verb} {n['id']}", [*paths, w.LOG, *extra_paths])
            progress.forget(n["id"])
        summary[verb] += 1

    # 1. route, one note at a time, so a later note sees the pages planned by an earlier one
    targets, planned = {}, {}
    for n in notes:
        if norm_hash(n["body"]) in seen:
            settle(n, "discard", f"discard {n['id']}: same text as an earlier note")
            continue
        try:
            r = route(llm, n, folders, planned)
        except (RuntimeError, ValueError) as e:
            r = {"action": "pending", "why": str(e)}
        n["route"] = r
        if r["action"] == "merge":
            n["needs"] = set(r["pages"])
            for pid in r["pages"]:
                if pid in planned:
                    planned[pid]["notes"].append(n)
                elif pid not in progress.done(n["id"]):
                    targets.setdefault(pid, []).append(n)
        elif r["action"] == "new":
            key = f"{r['folder']}/{r['slug']}"
            if w.resolve(key):                      # the slug already exists: merge into it
                key = w.page_id(w.resolve(key))
                targets.setdefault(key, []).append(n)
            elif key in planned:
                planned[key]["notes"].append(n)
            else:
                planned[key] = {"title": r.get("title") or n["meta"].get("title"), "notes": [n],
                                "related": r.get("related")}
            n["needs"] = {key}
        elif r["action"] == "question":
            with git_lock():
                add_question(r, n)
            settle(n, "question", f"question {n['id']} → status.md: {r.get('question', '')}", [w.ROOT / "status.md"])
        elif r["action"] == "discard":
            settle(n, "discard", f"discard {n['id']}: {r.get('why', '')}")
        else:
            out(f"  {n['id']}: left in the inbox ({r['why'][:120]})")
            summary["pending"] += 1

    page_ids = sorted({w.page_id(p) for p in w.pages()} | set(planned))
    vcfg = verify.settings()
    written = set()
    max_chars = int((c.get("llm") or {}).get("max_page_chars", 30000))

    def knock_on(pid, old, page):
        """The cases code can't settle, for the agent check (C): a new or changed disagreement on this page, and up
        to KNOCK_ON_MAX_PAGES other pages that still hold a value this merge replaced (a value on more than
        KNOCK_ON_MAX_SPREAD other pages is too common to mean anything). Returns {page: reason}."""
        reasons = {}
        old_body, new_body = w.split(old)[1] if old else "", w.split(page)[1]
        d_old, d_new = DISAGREE.search(old_body), DISAGREE.search(new_body)
        if d_new and (not d_old or d_old.group(1).strip() != d_new.group(1).strip()):
            reasons[pid] = "disagreement recorded: settle it or make it an open question"
        replaced = [f for f in facts(old_body) - facts(new_body)
                    if len(f.strip("`")) >= 4 and not YEARISH.match(f.strip("`"))]
        others = {w.page_id(p): p.read_text(encoding="utf-8") for p in w.pages() if w.page_id(p) != pid}
        hits = {}
        for f in sorted(replaced):
            where = [oid for oid, text in others.items() if f in text]
            if 0 < len(where) <= KNOCK_ON_MAX_SPREAD:
                for oid in where:
                    hits.setdefault(oid, []).append(f)
        for oid, vals in sorted(hits.items())[:KNOCK_ON_MAX_PAGES]:
            reasons[oid] = f"may still say {', '.join(vals[:5])} (replaced on {pid})"
        return reasons

    def file(pid, page, why, notes_here, verb, old, gaps=None):
        """Compare-and-swap write, A/B/C bookkeeping, log, a commit of just these files; then file the notes whose
        every page is in. Returns False when the page changed under us (the caller merges again)."""
        path = w.ROOT / f"{pid}.md"
        listed, tag = {}, ""
        gaps = gaps or {}
        if vcfg["enabled"]:                         # A + B: a page keeps `verified` only when code checked every note
            per_note = [verify.check(n["path"], n["meta"], n["body"]) for n in notes_here]
            results = [r for res in per_note for r in res]
            ok = all(verify.passed(res) for res in per_note)
            listed = knock_on(pid, old, page)
            if not ok:
                listed.setdefault(pid, "unchecked: " + verify.summary(results))
            meta, body = w.split(page)
            if pid in listed and meta.get("status") == "verified":
                meta["status"] = "draft"
                page = w.dump(meta, body)
            if gaps:
                listed.setdefault(pid, "facts of the notes on no page: " + "; ".join(
                    f"{k}: {', '.join(v[:8])}" for k, v in gaps.items())[:400])
            tag = (f" [{'checked' if ok else 'unchecked'}: {verify.summary(results)}"
                   + "".join(f"; {k}: {v}" for k, v in listed.items() if k != pid) + "]")
        if gaps:
            summary["gaps"] = summary.get("gaps", 0) + sum(map(len, gaps.values()))
        with git_lock():
            now = path.read_text(encoding="utf-8") if path.exists() else None
            if now != old:                          # someone edited (or created) the page while the model worked
                return False
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(page, encoding="utf-8")
            written.add(pid)
            for n in notes_here:
                gap = f" [on no page: {', '.join(gaps[n['id']][:10])}]" if n["id"] in gaps else ""
                w.append_log("steward", f"{verb} {n['id']} → {pid}: {why}{tag}{gap}")
                progress.add(n["id"], pid)
            commit(f"steward: {verb} {len(notes_here)} note(s) into {pid}", [path, w.LOG])
        for oid, reason in listed.items():          # after the write: the entry records the page as written
            verify.add(oid, [n["id"] for n in notes_here], reason)
        for n in notes_here:                        # a note leaves the inbox once every page it feeds is in
            if n.get("needs") and n["needs"] <= progress.done(n["id"]) and n["path"].exists():
                settle(n, "new" if n["route"]["action"] == "new" else "merged",
                       f"filed {n['id']} ({', '.join(sorted(n['needs']))})")
        return True

    def fail(notes_here, why):
        for n in notes_here:
            n["failed"] = why

    def last_page_for(pid, notes_here):
        """The notes whose every other page is already in: their coverage is checked on this merge."""
        return [n for n in notes_here if (n.get("needs") or set()) - {pid} <= progress.done(n["id"])]

    def merge_into(pid, notes_here):
        """Merge these notes into an existing page (compare-and-swap: once more on a newer text). Returns "ok",
        "model" (the model's replies failed the checks) or "other"."""
        for _try in range(2):
            path = w.resolve(pid)
            if not path:
                fail(notes_here, f"{pid} is gone (renamed or merged): routed again next run")
                return "other"
            old = path.read_text(encoding="utf-8")
            if len(old) > max_chars:
                fail(notes_here, f"{pid} is too big for the pipeline ({len(old)} chars)")
                return "other"
            try:
                page, why, gaps = edit_page(llm, pid, notes_here, agent, page_ids, old, last_page_for(pid, notes_here))
            except RuntimeError as e:
                fail(notes_here, f"{pid}: {e}")
                return "other"
            if not page:
                fail(notes_here, f"{pid}: {why}")
                return "model"
            if file(pid, page, why, notes_here, "merge", old, gaps):
                return "ok"
            out(f"  {pid} changed while it was being merged: merging again on the new text")
        fail(notes_here, f"{pid} kept changing while it was being merged")
        return "other"

    overflow = (c.get("llm") or {}).get("overflow") or ("agent" if c.get("rest", "agent") == "agent" else "split")

    def continuation(pid):
        """The first of <pid>-2, <pid>-3, … that does not exist yet or still has room."""
        for k in range(2, 100):
            cand = f"{pid}-{k}"
            p = w.resolve(cand)
            if cand in planned or not p or len(p.read_text(encoding="utf-8")) <= max_chars:
                return cand
        return None

    for pid, notes_here in list(targets.items()):
        path = w.resolve(pid)
        if overflow == "split" and path and len(path.read_text(encoding="utf-8")) > max_chars:
            cont = continuation(pid)               # a full page: its new notes go to a linked continuation page
            if cont:
                for n in notes_here:
                    n["needs"] = (n.get("needs") or set()) - {pid} | {cont}
                if cont not in page_ids:
                    page_ids = sorted(set(page_ids) | {cont})
                if not w.resolve(cont):
                    title = w.split(path.read_text(encoding="utf-8"))[0].get("title") or pid
                    planned.setdefault(cont, {"title": f"{title} (continued)", "notes": [],
                                              "related": pid})["notes"].extend(notes_here)
                    out(f"  {pid} is full ({max_chars} chars): {len(notes_here)} note(s) go to the new page {cont}")
                    continue
                out(f"  {pid} is full: merging into its continuation {cont}")
                pid = cont
        if merge_into(pid, notes_here) == "model" and len(notes_here) > 1:
            out(f"  {pid}: the merge of {len(notes_here)} notes failed; merging them one at a time")
            for n in notes_here:                    # a smaller task often passes where the group did not
                n.pop("failed", None)
                merge_into(pid, [n])

    for pid, spec in planned.items():
        try:
            page, why, gaps = new_page(llm, pid, spec["title"], spec["notes"], agent, page_ids,
                                       last_page_for(pid, spec["notes"]))
        except RuntimeError as e:
            page, why, gaps = None, str(e), {}
        if not page:
            fail(spec["notes"], f"new {pid}: {why}")
            continue
        if not file(pid, page, why, spec["notes"], "new", None, gaps):
            fail(spec["notes"], f"{pid} appeared while it was being written: routed again next run")
            continue
        rel = w.resolve(str(spec.get("related") or ""))
        if rel and rel.suffix == ".md" and "inbox" not in rel.parts:     # link the new page from a related one
            with git_lock():
                text = rel.read_text(encoding="utf-8")
                if f"[[{pid}]]" not in text:
                    rel.write_text(text.rstrip("\n") + f"\n\nSee also [[{pid}]].\n", encoding="utf-8")
                    commit(f"steward: link {pid} from {w.page_id(rel)}", [rel])

    # 3. split: a page this run made too big has whole sections moved where that kind of fact belongs
    split_chars = int((c.get("llm") or {}).get("split_page_chars", SPLIT_CHARS))
    queue, calls = sorted(written), 0
    while split_chars and queue and calls < MAX_SPLITS:
        pid = queue.pop(0)
        path = w.resolve(pid)
        if not path or len(path.read_text(encoding="utf-8")) <= split_chars:
            continue
        text = path.read_text(encoding="utf-8")
        calls += 1
        try:
            moves, why = plan_split(llm, pid, text, split_chars)
        except (RuntimeError, ValueError) as e:
            moves, why = [], str(e)
        if not moves:
            out(f"  {pid}: {len(text)} chars, not split ({why[:120]})")
            continue
        files = apply_split(pid, text, moves, agent)
        with git_lock():
            if path.read_text(encoding="utf-8") != text:
                continue
            for p, t in files.items():
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(t, encoding="utf-8")
            w.append_log("steward", f"split {pid} ({len(text)} chars): " + "; ".join(
                f"{h[3:]} → {to}" for h, to, _ in moves) + (f" ({why})" if why else ""))
            commit(f"steward: split {pid}", [*files, w.LOG])
        summary["split"] = summary.get("split", 0) + 1
        out(f"  {pid}: split, {len(moves)} section(s) moved")
        queue += [w.page_id(p) for p in files]          # the page and its targets may still be too big

    for n in notes:
        if n["path"].exists() and n.get("route") and n["route"]["action"] in ("merge", "new"):
            why = n.get("failed") or "not all of its pages were merged"
            out(f"  {n['id']}: left in the inbox ({why[:160]})")
            with git_lock():
                w.append_log("steward", f"pending {n['id']}: {why[:200]}")
                commit("steward: pending note", [w.LOG])
            summary["pending"] += 1

    result = {"type": "result", "is_error": False, "num_turns": llm.calls, "duration_ms": int((time.time() - t0) * 1000),
              "total_cost_usd": 0, "usage": {**llm.usage, "cache_creation_input_tokens": 0, "cache_read_input_tokens": 0},
              "result": "pipeline steward: " + ", ".join(f"{k} {v}" for k, v in summary.items()), "summary": summary}
    logs = w.ROOT / "logs"
    logs.mkdir(exist_ok=True)
    (logs / f"steward-{run_tag()}.json").write_text(json.dumps(result) + "\n", encoding="utf-8")
    out(result["result"] + f" ({llm.calls} LLM calls, {llm.usage['input_tokens']:,} in / "
        f"{llm.usage['output_tokens']:,} out tokens, {llm.seconds:.0f} s)")
    return 1 if summary["pending"] else 0
