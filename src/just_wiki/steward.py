"""The steward: an LLM agent that merges inbox notes into pages and re-checks stale pages, plus the nightly run around it.

The procedure ships with just-wiki (templates/steward.md); a wiki adds its own rules in STEWARD.md at its root
([steward] rules). `just-wiki steward --install` writes both into .claude/skills/wiki-steward/SKILL.md, so a Claude
Code session in the wiki can run `/wiki-steward`, and so can the headless command in [steward] command (default:
`claude -p /wiki-steward`). `{root}` in a command is the wiki root.

  just-wiki steward             run the steward once now (lint, commit after), if anything waits
  just-wiki steward --force     run it even when nothing waits
  just-wiki steward --print     print the full steward prompt (for agents other than Claude Code)
  just-wiki nightly             live blocks, brief, lint, the steward when needed, push, report
"""
import fcntl
import json
import os
import re
import subprocess
import sys
import time
from contextlib import contextmanager
from datetime import date
from importlib import resources
from pathlib import Path

from . import brief, config, lint, live, questions
from . import store as w

DEFAULT_COMMAND = ["claude", "-p", "/wiki-steward{scope}", "--output-format", "json", "--permission-mode", "auto",
                   "--max-turns", "200"]
SCOPES = ("notes", "questions", "stale", "unchecked", "gaps")
STEWARD_ACTS = re.compile(r"^- \[[^]]*\] steward \| ([a-z]+)\b")


STEPS = {"notes": ("2", "3"), "stale": ("4",), "unchecked": ("4b",), "gaps": ("4c",), "questions": ("5",)}


def scoped(text, only):
    """The procedure with only the steps a scoped run needs (1, 6-8 always): a smaller prompt for every call of a
    run limited to e.g. questions, which matters for small local models."""
    head, sep, rest = text.partition("## Procedure\n")
    body, sep2, tail = rest.partition("\n## ")
    keep = {"1", "6", "7", "8"} | {x for s in only for x in STEPS.get(s, ())}
    parts = re.split(r"(?m)^(?=\d+[a-z]?\. )", body)
    kept = [p for p in parts if not re.match(r"\d+[a-z]?\. ", p) or re.match(r"(\d+[a-z]?)\. ", p).group(1) in keep]
    return head + sep + "".join(kept) + sep2 + tail


def prompt(only=None):
    from . import verify
    text = resources.files("just_wiki").joinpath("templates/steward.md").read_text(encoding="utf-8")
    text = text.replace("{per_run}", str(verify.settings()["per_run"])).replace("{page_dirs}", " ".join(w.PAGE_DIRS))
    only = [x for x in (only or []) if x in SCOPES]
    if only and set(only) != set(SCOPES):
        text = scoped(text, only)
    rules = w.ROOT / w.cfg()["steward"]["rules"]
    if rules.is_file():
        text += "\n## Rules of this wiki\n\n" + rules.read_text(encoding="utf-8").strip() + "\n"
    return text


def install():
    """Write the steward skill for Claude Code into the wiki. Returns its path."""
    f = w.ROOT / ".claude/skills/wiki-steward/SKILL.md"
    f.parent.mkdir(parents=True, exist_ok=True)
    text = ("---\nname: wiki-steward\ndescription: Merge pending inbox notes into this wiki, re-check stale pages, "
            "lint and commit. Generated by just-wiki from its steward procedure and this wiki's STEWARD.md; "
            "do not edit.\n---\n\n" + prompt())
    if not f.exists() or f.read_text(encoding="utf-8") != text:
        f.write_text(text, encoding="utf-8")
    return f


@contextmanager
def run_lock(wait_s=1800):
    """One steward run at a time (nightly, --due, the web UI's "run now", the agent rest). Yields True when this
    run holds the lock, False when another run kept it for wait_s seconds (0: don't wait)."""
    f = w.ROOT / "logs" / "steward.lock"
    f.parent.mkdir(exist_ok=True)
    with open(f, "w") as fh:
        t = time.time()
        while True:
            try:
                fcntl.flock(fh, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                if time.time() - t >= wait_s:
                    yield False
                    return
                time.sleep(5)
        try:
            yield True
        finally:
            fcntl.flock(fh, fcntl.LOCK_UN)


@contextmanager
def git_lock():
    """One git writer at a time in the wiki (the steward run, the nightly commit, other tools that commit)."""
    f = w.ROOT / "logs" / "git.lock"
    f.parent.mkdir(exist_ok=True)
    with open(f, "w") as fh:
        fcntl.flock(fh, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(fh, fcntl.LOCK_UN)


def git(*args, check=False):
    return subprocess.run(["git", "-C", str(w.ROOT), *args], capture_output=True, text=True, check=check)


def commit(message):
    """Commit everything in the wiki if anything changed. True when a commit was made."""
    if not (w.ROOT / ".git").exists():
        return False
    git("add", "-A")
    if git("diff", "--cached", "--quiet").returncode == 0:
        return False
    return git("commit", "-qm", message).returncode == 0


def quiet(fn, **kw):
    lines = []
    try:
        rc = fn(out=lines.append, **kw)
    except SystemExit as err:
        lines.append(str(err))
        rc = 1
    return rc, lines


def extra_pending():
    """Sum of the numbers printed by [steward] pending_commands (other work that should start the steward)."""
    total = 0
    for cmd in w.cfg()["steward"]["pending_commands"]:
        try:
            out = subprocess.run([config.expand(a, w.ROOT) for a in cmd], capture_output=True, text=True,
                                 timeout=120, cwd=w.ROOT).stdout.strip()
            total += int(out.split()[0]) if out else 0
        except (OSError, ValueError, subprocess.TimeoutExpired):
            pass
    return total


def waiting():
    """What would start the steward: inbox notes (answers to questions among them), other work from
    pending_commands, open questions it should settle by itself (due reminders, agent-owned), stale pages."""
    from . import stats, verify
    answers = sum(len(v) for v in questions.answers().values())
    unchecked = len(verify.reconcile()) if verify.settings()["enabled"] else 0
    return {"notes": len(w.inbox_notes()) - answers, "answers": answers, "other": extra_pending(),
            "questions": sum(questions.needs_steward(q) for q in questions.rows()), "stale": len(lint.stale_pages()),
            "unchecked": unchecked, "gaps": len(stats.open_gaps())}


def scope_arg(only):
    """' only: notes,questions' for the steward prompt, '' for a full run."""
    only = [x for x in (only or []) if x in SCOPES]
    return f" only: {','.join(only)}" if only and set(only) != set(SCOPES) else ""


def run_agent(tag, only=None):
    """Run the configured steward command; output in logs/steward-<tag>.json/.err. Returns its exit code.
    {scope} in the command becomes ' only: …' when the run is limited to some of notes, questions, stale."""
    install()
    scope = scope_arg(only)
    cmd = [config.expand(a, w.ROOT).replace("{scope}", scope)
           for a in (w.cfg()["steward"]["command"] or DEFAULT_COMMAND)]
    logs = w.ROOT / "logs"
    logs.mkdir(exist_ok=True)
    state = logs / "steward-run.json"
    head = git("rev-parse", "HEAD").stdout.strip() if (w.ROOT / ".git").exists() else ""
    log_lines = len(w.LOG.read_text(encoding="utf-8").splitlines()) if w.LOG.exists() else 0
    state.write_text(json.dumps({"started": w.now(), "pid": os.getpid(), "running": True, "scope": scope.strip(),
                                 "head": head, "log_lines": log_lines, "tag": tag}) + "\n")
    rc = 1
    try:
        with open(logs / f"steward-{tag}.json", "w") as out, open(logs / f"steward-{tag}.err", "w") as err:
            rc = subprocess.run(cmd, stdout=out, stderr=err, cwd=w.ROOT, stdin=subprocess.DEVNULL,
                                timeout=int(w.cfg()["steward"]["timeout_min"]) * 60).returncode
    except subprocess.TimeoutExpired:
        rc = 124
    except OSError as e:
        msg = (f"could not start {cmd[0]}: {e}\nThe agent steward needs that command ([steward] command in wiki.toml; "
               "default: Claude Code). Without it, set mode = \"pipeline\" and a [steward.llm] endpoint, or run another "
               "agent that can follow STEWARD.md.\n")
        (logs / f"steward-{tag}.err").write_text(msg)
        print(msg, file=sys.stderr, end="")
        rc = 127
    for cmd in w.cfg()["steward"]["after"]:   # e.g. carry out decisions the steward recorded
        subprocess.run([config.expand(a, w.ROOT) for a in cmd], cwd=w.ROOT)
    s = json.loads(state.read_text())
    state.write_text(json.dumps({**s, "ended": w.now(), "rc": rc, "running": False}) + "\n")
    return rc


def running():
    """The state of the last steward run (logs/steward-run.json), with running=False if its process is gone."""
    f = w.ROOT / "logs" / "steward-run.json"
    try:
        s = json.loads(f.read_text())
    except (OSError, ValueError):
        return {"running": False}
    if s.get("running") and s.get("pid") and not Path(f"/proc/{s['pid']}").exists():
        s["running"] = False
    return s


def describe(wait):
    return (f"{wait['notes']} note(s), {wait['answers']} answer(s), {wait['questions']} question(s) to settle, "
            f"{wait['other']} other, {wait['stale']} stale page(s), {wait.get('unchecked', 0)} unchecked page(s), "
            f"{wait.get('gaps', 0)} search gap(s)")


def steward_once(force=False, only=None, out=print):
    w.require_root()
    with run_lock() as mine:
        if not mine:
            out("another steward run kept the lock for 30 min: not starting a second one")
            return 0
        return _steward_once(force, only, out)


def _steward_once(force=False, only=None, out=print):
    wait = waiting()
    relevant = {"notes": wait["notes"] + wait["other"], "questions": wait["answers"] + wait["questions"],
                "stale": wait["stale"], "unchecked": wait.get("unchecked", 0), "gaps": wait.get("gaps", 0)}
    if not force and not any(v for k, v in relevant.items() if not only or k in only):
        out("nothing waiting: no inbox notes, no questions to settle, no other work, no stale pages")
        return 0
    out(f"{describe(wait)}: running the steward" + (f" (only {', '.join(only)})" if only else ""))
    c = w.cfg()["steward"]
    if c.get("mode") == "pipeline":
        rc = pipeline_once(wait, only, out)
    else:
        rc = run_agent(time.strftime("%Y-%m-%d-%H%M%S"), only)
    quiet(lint.run, fix=True)
    with git_lock():
        commit("lint (after steward)")
    out(f"steward finished with exit code {rc}")
    return rc


def pipeline_once(wait, only, out):
    """[steward] mode = "pipeline": notes are merged by the pipeline (small LLM calls, code for the rest); answers,
    questions to settle and stale pages go to the agent steward when [steward] rest = "agent"."""
    from . import pipeline
    rc = 0
    if not only or "questions" in only:          # owner / postpone / drop answers: table edits, no model needed;
        if pipeline.mechanical_answers(out=out) + pipeline.decision_answers(out=out):   # decide → a note
            answers = sum(len(v) for v in questions.answers().values())
            wait = {**wait, "answers": answers, "notes": len(w.inbox_notes()) - answers}
    if (not only or "notes" in only) and wait["notes"]:
        rc = pipeline.run(out=out)
    from . import verify
    wait = {**wait, "unchecked": len(verify.reconcile()) if verify.settings()["enabled"] else 0}   # after the merge
    need = {"questions": wait["answers"] + wait["questions"], "stale": wait["stale"], "unchecked": wait["unchecked"],
            "gaps": wait.get("gaps", 0)}
    rest = [s for s in ("questions", "stale", "unchecked", "gaps") if (not only or s in only) and need[s]]
    if rc:                                # notes the pipeline could not place: the agent steward takes them tonight
        rest.insert(0, "notes")
        rc = 0
    if rest and w.cfg()["steward"].get("rest") == "agent":
        out(f"agent steward for {', '.join(rest)}")
        before = set(verify.reconcile()) if "unchecked" in rest else set()
        rc = max(rc, run_agent(time.strftime("%Y-%m-%d-%H%M%S") + "-agent", rest))
        if before:                                  # tried but still listed: not due again for RETRY_HOURS
            verify.mark_tried(before & set(verify.reconcile()))
    return rc


def due(out=print):
    """`just-wiki steward --due`, for a frequent timer: run the agent check (C) only when an unchecked page has
    waited [steward.verify] max_wait_min; otherwise do nothing (cheap)."""
    from . import verify
    w.require_root()
    if not verify.settings()["enabled"]:
        return 0
    late = verify.due()
    if not late:
        return 0
    with run_lock(wait_s=0) as mine:            # a steward run is going: it takes the list itself, don't queue up
        if not mine:
            return 0
        out(f"{len(late)} unchecked page(s) waited {verify.settings()['max_wait_min']} min or more: agent check now")
        rc = run_agent(time.strftime("%Y-%m-%d-%H%M%S") + "-due", ["unchecked"])
        verify.mark_tried(set(late) & set(verify.reconcile()))
        quiet(lint.run, fix=True)
        with git_lock():
            commit("lint (after the agent check)")
        return rc


def nightly(out=print):
    """The nightly run. Writes logs/nightly.json and hands it to [nightly] report_command."""
    w.require_root()
    c = w.cfg()["nightly"]
    today = date.today().isoformat()
    log_start = len(w.LOG.read_text(encoding="utf-8").splitlines()) if w.LOG.exists() else 0
    problems = []
    with git_lock():
        for name, fn in (("live", live.run), ("brief", brief.run)):
            rc, lines = quiet(fn)
            if rc:
                problems.append(f"{name} failed: {' '.join(lines)[:200]}")
        quiet(lint.run, fix=True)
        commit("lint (nightly)")
    if w.cfg()["memory"].get("enabled") and w.cfg()["memory"].get("nightly"):   # optional: agents' memories vs. the wiki
        from . import memory
        rc_m, lines = quiet(memory.nightly)
        if rc_m:
            problems.append(f"memory failed: {' '.join(lines)[:200]}")
    wait = waiting()
    rc = 0
    if any(wait.values()):
        out(f"{describe(wait)}: running the steward")
        rc = run_agent(today)
    else:
        out("nothing waiting for the steward")
    rc_b, lines = quiet(brief.run)   # again: the steward may have changed a brief snippet
    if rc_b:
        problems.append(f"brief failed: {' '.join(lines)[:200]}")
    _, lint_lines = quiet(lint.run, fix=True)
    pushed = None
    with git_lock():
        commit("lint (after steward)")
        if c["push"] and git("remote").stdout.strip():
            pushed = git("pull", "-q", "--rebase", c["remote"], c["branch"]).returncode == 0
            if not pushed:
                git("rebase", "--abort")
            else:
                pushed = git("push", "-q", c["remote"], c["branch"]).returncode == 0
    new_log = (w.LOG.read_text(encoding="utf-8").splitlines() if w.LOG.exists() else [])[log_start:]
    acts = {}
    for line in new_log:
        m = STEWARD_ACTS.match(line)
        if m:
            acts[m.group(1)] = acts.get(m.group(1), 0) + 1
    summary = {"date": today, "waiting": wait, "steward_rc": rc if any(wait.values()) else None, "acts": acts,
               "stale_left": len(lint.stale_pages()), "lint": lint_lines[-1] if lint_lines else "",
               "lint_lines": lint_lines[:-1], "pushed": pushed, "problems": problems,
               "status_questions": count_open_questions()}
    f = w.ROOT / "logs" / "nightly.json"
    f.write_text(json.dumps(summary, ensure_ascii=False, indent=1) + "\n")
    out(json.dumps(summary, ensure_ascii=False))
    if c["report_command"]:
        subprocess.run([config.expand(a, w.ROOT) for a in c["report_command"]] + [str(f)], cwd=w.ROOT)
    return rc


def open_questions():
    """[{question, owner}] of status.md's Open questions (see just_wiki.questions for the full rows)."""
    return [{"question": q["text"], "owner": q["owner"]} for q in questions.rows()]


def count_open_questions():
    """Open questions waiting for the wiki's owner, not yet answered."""
    answered = questions.answers()
    return sum(1 for q in questions.rows() if q["kind"] == "mine" and q["id"] not in answered)
