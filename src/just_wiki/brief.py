"""The brief: the facts agents ask about most, in one short text that sits in every agent's context.

Agents follow what is already in their context far more reliably than what they must look up, and a fact they have
needs no copy in their memory. So the brief is generated (nightly) and copied to where each agent loads it.

Content, in the order of [brief] sections:
  "howto"           the lines pages mark with <!-- brief -->…<!-- /brief --> (the page owns them)
  "folder:<name>"   every page of that folder (e.g. preferences: standing instructions belong in context), each
                    trimmed so the whole brief stays under max_chars
  ["cmd", "arg"…]   a command whose stdout is one Markdown section (e.g. facts read from the host)
Targets ([[brief.targets]]): `path`, and `mode` = "file" (the whole file is the brief, default) or "block" (only
between <!-- brief --> and <!-- /brief --> in an existing file); optional `prefix` text before the brief.
brief.md in the wiki root is always written; lint fails when it is edited by hand. A brief over max_chars fails.

  just-wiki brief            write all targets
  just-wiki brief --show     print the brief
  just-wiki brief --check    exit 1 if a target differs from what would be written
"""
import hashlib
import json
import re
import subprocess
from pathlib import Path

from . import config
from . import store as w

MARK = re.compile(r"<!-- brief -->\n(.*?)<!-- /brief -->", re.S)
TARGET_BLOCK = re.compile(r"(<!-- brief -->\n)(.*?)(<!-- /brief -->)", re.S)
DEFAULT_HEAD = ("# Brief\n\nGenerated by `just-wiki brief` from the wiki: it is current. Never edit it and never "
                "copy its values into memory; anything not here is in the wiki.\n")


def howto_section():
    parts = []
    for page in w.pages():
        for m in MARK.finditer(page.read_text(encoding="utf-8")):
            parts.append(m.group(1).rstrip() + f" (wiki `{w.page_id(page)}`)")
    return "## How to\n\n" + "\n".join(parts) + "\n" if parts else ""


def folder_section(folder, room):
    """The pages of one folder as one section, each page's body without its title line, cut to fit `room`."""
    d = w.ROOT / folder
    pages = sorted(d.glob("*.md")) if d.is_dir() else []
    if not pages or room <= 200:
        return ""
    each = max(200, (room - 100) // len(pages))
    out = [f"## {folder.capitalize()}\n"]
    for p in pages:
        meta, body = w.split(p.read_text(encoding="utf-8"))
        body = re.sub(r"(?m)^# .*\n?", "", body).strip()
        body = re.sub(r"(?m)^(#+) ", lambda m: "#" * min(6, len(m.group(1)) + 2) + " ", body)
        if len(body) > each:
            body = body[:each].rsplit(" ", 1)[0] + f" … (more: `{w.page_id(p)}`)"
        out.append(f"### {meta.get('title') or w.page_id(p)} (`{w.page_id(p)}`)\n\n{body}\n")
    return "\n".join(out)


def command_section(cmd):
    argv = [config.expand(a, w.ROOT) for a in cmd]
    r = subprocess.run(argv, capture_output=True, text=True, timeout=120, cwd=w.ROOT)
    if r.returncode != 0:
        raise SystemExit(f"brief: section command {argv[0]} exited {r.returncode}: {r.stderr.strip()[:300]}")
    return r.stdout


def build():
    c = w.cfg()["brief"]
    parts = [c["head"] or DEFAULT_HEAD]
    for s in c["sections"]:
        if isinstance(s, str) and s.startswith("folder:"):
            part = folder_section(s.split(":", 1)[1], int(c["max_chars"]) - sum(map(len, parts)) - 50)
        else:
            part = howto_section() if s == "howto" else command_section(s)
        if part:
            parts.append(part)
    text = "\n".join(parts)
    if w.SECRET.search(text):
        raise SystemExit("brief: the brief looks like it holds a secret; not written")
    if len(text) > int(c["max_chars"]):
        raise SystemExit(f"brief: the brief is {len(text)} characters, over the {c['max_chars']} cap; shorten a "
                         "<!-- brief --> snippet or drop a section")
    return text


def targets(text):
    """{path: new content} for every target."""
    out = {w.ROOT / "brief.md": text}
    for t in w.cfg()["brief"]["targets"]:
        p = Path(config.expand(t["path"], w.ROOT))
        full = t.get("prefix", "") + text
        if t.get("mode", "file") == "block":
            if not p.exists():
                continue
            cur = p.read_text(encoding="utf-8")
            out[p] = (TARGET_BLOCK.sub(lambda m, f=full: m.group(1) + f + m.group(3), cur) if TARGET_BLOCK.search(cur)
                      else cur.rstrip("\n") + f"\n\n<!-- brief -->\n{full}<!-- /brief -->\n")
        else:
            out[p] = full
    return out


def run(show=False, check=False, out=print):
    w.require_root()
    text = build()
    if show:
        out(text)
        return 0
    t = targets(text)
    if check:
        stale = [str(p) for p, c in t.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
        if stale:
            out("brief out of date or edited by hand: " + ", ".join(stale))
            return 1
        out("brief ok")
        return 0
    for p, c in t.items():
        if not p.exists() or p.read_text(encoding="utf-8") != c:
            p.write_text(c, encoding="utf-8")
    state = w.ROOT / "logs/brief.json"
    state.parent.mkdir(exist_ok=True)
    state.write_text(json.dumps({"written": w.now(), "chars": len(text),
                                 "sha256": hashlib.sha256(text.encode()).hexdigest()}) + "\n")
    out(f"brief: {len(text)} characters, written to {len(t)} targets")
    return 0
